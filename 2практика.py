# -*- coding: utf-8 -*-                                       # кодировка файла
import math                                                  # импортируем модуль math для проверки квадрата

print("Проверка характеристик числа")                        # заголовок программы

while True:                                                  # бесконечный цикл для повторения действий
    raw = input("\nВведите число: ")                         # ввод числа (строка), \n для отступа
    try:                                                     # пробуем преобразовать в целое
        n = int(raw)                                         # строка -> целое число
    except ValueError:                                       # если не число
        print("Ошибка: это не число. Попробуйте снова.")     # сообщение об ошибке
        continue                                             # возвращаемся в начало цикла, не выходим

    print("Ваше число:", n)                                  # выводим само число

    if n > 0:                                                # проверка на положительное
        print("Положительное: да")                           # если больше нуля
    elif n < 0:                                              # проверка на отрицательное
        print("Положительное: нет")                          # если меньше нуля
    else:                                                    # иначе — ноль
        print("Положительное: нет")                          # ноль не положительное

    if n == 0:                                               # проверка на ноль
        print("Отрицательное: нет")                          # ноль не отрицательное
    elif n < 0:                                              # если меньше нуля
        print("Отрицательное: да")                           # значит отрицательное
    else:                                                    # иначе
        print("Отрицательное: нет")                          # положительное

    if n == 0:                                               # отдельно проверяем ноль
        print("Ноль: да")                                    # это ноль
    else:                                                    # иначе
        print("Ноль: нет")                                   # не ноль

    if n % 2 == 0:                                           # проверка на чётность
        print("Четное: да")                                  # остаток от деления на 2 равен 0
    else:                                                    # иначе
        print("Четное: нет")                                 # нечётное

    if n % 3 == 0:                                           # проверка делимости на 3
        print("Делится на 3: да")                            # остаток равен 0
    else:                                                    # иначе
        print("Делится на 3: нет")                           # не делится

    if n % 5 == 0:                                           # проверка делимости на 5
        print("Делится на 5: да")                            # остаток равен 0
    else:                                                    # иначе
        print("Делится на 5: нет")                           # не делится

    is_prime = True                                          # предполагаем, что число простое
    if n < 2:                                                # числа меньше 2 не простые
        is_prime = False                                     # значит не простое
    else:                                                    # иначе проверяем делители
        for i in range(2, int(n ** 0.5) + 1):                # перебираем от 2 до корня из n
            if n % i == 0:                                   # если делится без остатка
                is_prime = False                             # значит не простое
                break                                        # дальше проверять не нужно

    if is_prime:                                             # если простое
        print("Простое: да")                                 # выводим да
    else:                                                    # иначе
        print("Простое: нет")                                # выводим нет

    count = len(str(abs(n)))                                 # количество цифр (модуль, чтобы минус не считался)
    print("Количество цифр:", count)                         # выводим количество цифр

    # НОВЫЙ ФУНКЦИОНАЛ: Проверка на полный квадрат
    if n >= 0:                                               # квадрат бывает только у неотрицательных
        root = int(math.isqrt(n))                            # берем целый корень
        if root * root == n:                                 # проверяем, даёт ли корень при умножении на себя исходное число
            print("Полный квадрат: да")                      # если да
        else:                                                # иначе
            print("Полный квадрат: нет")                     # если нет
    else:                                                    # для отрицательных чисел
        print("Полный квадрат: нет")                         # квадрата нет

    # Спрашиваем, хочет ли пользователь продолжить
    answer = input("Проверить ещё одно число? (да/нет): ").strip().lower() # ввод ответа
    if answer == "да":                                       # если "да"
        continue                                             # продолжаем цикл (спрашиваем число заново)
    elif answer == "нет":                                    # если "нет"
        print("Работа программы завершена.")                 # прощаемся
        break                                                # прерываем цикл (выходим из программы)
    else:                                                    # если ввели что-то другое
        while True:                                          # цикл для переспроса, пока не введут правильно
            print("Ошибка: введите 'да' или 'нет'.")         # сообщение об ошибке
            answer = input("Проверить ещё одно число? (да/нет): ").strip().lower() # переспрашиваем
            if answer == "да":                               # если "да"
                break                                        # выходим из внутреннего цикла
            elif answer == "нет":                            # если "нет"
                print("Работа программы завершена.")         # прощаемся
                exit()                                       # завершаем программу

